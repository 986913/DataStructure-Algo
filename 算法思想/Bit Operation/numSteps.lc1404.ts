/********************************* Solution 1: 原始直觉解法（无法全过）*********************************
  【核心思想】：直接将二进制字符串转为十进制整数，用数学逻辑模拟。
  【为什么优化】：JavaScript 的 Number 类型基于双精度浮点数， 
              最大安全整数为 2^53 - 1。而题目输入字符串长度可达 500
              当字符串过长时，parseInt 会丢失精度，导致死循环或错误答案
***************************************************************************************************/
function numStepsSolution1(s: string): number {
  // 将二进制字符串解析为十进制常规数字
  let decimal = parseInt(s, 2);

  let steps = 0;
  // 模拟题目要求的变化过程
  while (decimal !== 1) {
    if (decimal % 2 === 0) {
      decimal = decimal / 2; // 偶数除以 2
    } else {
      decimal += 1; // 奇数加 1
    }
    steps++;
  }

  return steps;
}

/********************************* Solution 2: BigInt 容错解法（能过，但非最优）************************
  【核心思想】：为了解决 Solution 1 的大数溢出问题，改用支持任意精度整数的 BigInt。
  【为什么优化】：虽然 BigInt 解决了正确性问题，但它本质上还是把整个大数存在内存中做除法和加法。
              高精度大数运算的底层实现非常耗时，每次循环都要处理几百位的数字，
              时间复杂度为 O(N^2)，在追求极致性能的面试中仍有优化空间。
***************************************************************************************************/
function numStepsSolution2(s: string): number {
  // 使用 BigInt 解析二进制字符串（"0b" 前缀代表二进制字面量）
  let decimal = BigInt('0b' + s);

  let steps = 0;
  // 注意：BigInt 必须与 BigInt 类型的字面量（如 1n, 2n, 0n）进行运算
  while (decimal !== 1n) {
    if (decimal % 2n === 0n) {
      decimal = decimal / 2n; // 偶数除以 2
    } else {
      decimal += 1n; // 奇数加 1
    }
    steps++;
  }

  return steps;
}

/********************************* Solution 3: 双 100% 的位模拟解法（最优解）************************
  【核心思想】：回归二进制的本质。二进制中：“除以 2” 等价于 “向右移一位”（去掉末尾的 0）
                                    “奇数加 1” 会在末尾产生进位，使当前的 1 变成 0，并向高位进 1。
            我们不需要真的去算这个大数是多少，只需要从右往左像做加法一样，
            用一个 carry 变量记录进位，一边遍历一边计算步数。
  【优化效果】：时间复杂度直降到 O(N)（只需遍历一次字符串），
            空间复杂度降到 O(1)（只需几个基础变量），速度和内存消耗达到最优。
*********************************/

function numStepsSolution3(s: string): number {
  let steps = 0;
  let carry = 0; // 记录低位加 1 产生的进位

  // 从右往左遍历，直到索引 1（最左边的 s[0] 留到循环外特殊处理）
  for (let i = s.length - 1; i > 0; i--) {
    // 当前位的值 = 字符实际值 + 低位传过来的进位
    let bit = Number(s[i]) + carry;
    if (bit === 1) {
      // 情况 A：当前位最终是 1（代表此时是个奇数）
      // 奇数需要：先加 1 变成偶数（1步），再除以 2 右移（1步），一共 2 步
      steps += 2;
      carry = 1; // 加 1 之后，向更高位产生了一个进位
    } else {
      // 情况 B：当前位最终是 0（原本是 0 且无进位）
      // 情况 C：当前位最终是 2（原本是 1 且有进位，1+1=2，当前位变 0 进位 1）
      // 这两种情况的共同点是：当前位处理完后都变成了“偶数末尾的0”，直接除以 2 右移即可（1步）
      steps += 1;
      // 如果 bit 是 2，carry 保持 1；如果 bit 是 0，carry 保持 0
    }
  }

  // 循环结束后，还剩下最左边的一位 s[0]（它初始必然是 '1'）
  // 如果最后 carry 还是 1，说明 s[0] 变成了 1 + 1 = 2（即二进制的 10），需要再除以 2（加 1 步）变成 1
  // 如果最后 carry 是 0，说明已经成功变成了 1，不需要额外步数
  return steps + carry;
}
