/***************************** 分段双指针 *********************************/
function minAvailableDuration(
  slots1: number[][],
  slots2: number[][],
  duration: number,
): number[] {
  let p1 = 0;
  let p2 = 0;

  // 💡 按照开始时间升序排序
  slots1.sort((a, b) => a[0] - b[0]);
  slots2.sort((a, b) => a[0] - b[0]);

  while (p1 < slots1.length && p2 < slots2.length) {
    const cur1 = slots1[p1];
    const cur2 = slots2[p2];

    const [start, end] = [
      Math.max(cur1[0], cur2[0]),
      Math.min(cur1[1], cur2[1]),
    ];

    if (start + duration <= end) {
      // Both have time
      return [start, start + duration];
    }

    /* =======================================================================
     * 🔥【重点攻克区域】：代码能走到这里，说明上面那个“完美重叠”的 if 失败了。
     *
     *  🚨 注意：失败并不意味着“完全没重叠”（Non-overlap）！
     *  此时空间上可能有 3 种情况：
     *    1. 完全不相交（如 [10,50] 和 [60,70]） -> 此时 start > end
     *    2. 部分相交但不够长（如 [10,50] 和 [45,70]） -> 此时相交 5 格，小于 duration(8)
     *    3. 包含但不够长（如 [10,100] 和 [40,45]） -> 此时相交 5 格，小于 duration(8)
     *
     *  💡【破局思维】：不管属于上面哪种情况，既然它们无法凑够 duration，
     *  那么“谁的结束时间更早”，谁在未来就彻底沦为了“废品”：
     * ======================================================================= */

    if (cur1[1] < cur2[1]) {
      // cur1 的右端点更靠左（先结束）。
      // 既然它在目前跟 cur2 亲密接触（不管是部分重叠还是完全不重叠）的情况下
      // 都榨不出足够的 duration，那它之后更不可能跟 cur2 后面的区间产生足够长的交集。
      // 结论：cur1 彻底作废，p1 往前走，寻找 Slots1 的下一个可能。
      p1++;
    } else if (cur1[1] > cur2[1]) {
      // cur2 的右端点更靠左（先结束）。
      // 同理，cur2 已经和当前这个长长的 cur1 试过了，依然无法满足 duration。
      // 说明 cur2 已经走到生命尽头，彻底失去价值。
      // 结论：cur2 彻底作废，p2 往前走。
      p2++;
    } else {
      // 两者的右端点正好在同一时间结束。
      // 这一秒过去之后，它们俩都属于过去式了，谁也无法和对方后面的新区间碰头。
      // 结论：打包一起带走，全部作废。
      p1++;
      p2++;
    }
  }

  return [];
}

/*
画面 1：完全不重叠（Non-overlapping）
  Slots1: [==== 10~50 ====]
  Slots2:                    [==== 60~70 ====]
                              ^
                              算出来的 start 在这里 (60)，而 end 在 50。
                              start > end，连 1 格重叠都没有！

画面 2：有重叠，但太短了！（Partial Overlap, too short
  Slots1: [======== 10~50 ========]
  Slots2:                  [======= 45~70 =======]
                          |=====|
                        重叠了 5 格 (45~50)，小于要求的 8 格！

画面 3：完全包含，但自身太短！（Contained, too short）
  Slots1: [=================== 10~100 ===================]
  Slots2:           [=== 40~45 ===]
                    |===========|
                  重叠了 5 格 (40~45)，Slots2 掏空了自己也凑不够 8 格！
*/
